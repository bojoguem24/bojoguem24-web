'use client'

import Link from 'next/link'
import { usePathname } from 'next/navigation'
import { cn } from '@/lib/utils'

const NAV_ITEMS = [
  { href: '/', label: '홈', icon: HomeIcon, exact: true },
  { href: '/subsidies', label: '검색', icon: SearchIcon, exact: false },
  { href: '/categories', label: '카테고리', icon: GridIcon, exact: false },
  { href: '/about', label: '소개', icon: InfoIcon, exact: false },
] as const

export function MobileNavBar() {
  const pathname = usePathname()

  return (
    <nav
      className="fixed inset-x-0 bottom-0 z-40 border-t border-gray-200 bg-white/95 backdrop-blur supports-[backdrop-filter]:bg-white/80 lg:hidden"
      style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}
      aria-label="하단 내비게이션"
    >
      <ul className="flex h-[var(--mobile-nav-height)] items-center">
        {NAV_ITEMS.map(({ href, label, icon: Icon, exact }) => {
          const active = exact
            ? pathname === href
            : pathname === href || pathname.startsWith(href + '/')
          return (
            <li key={href} className="flex-1">
              <Link
                href={href}
                className={cn(
                  'flex h-full flex-col items-center justify-center gap-0.5 px-1 text-[11px] font-medium transition',
                  active ? 'text-primary-600' : 'text-gray-500 hover:text-gray-700'
                )}
                aria-current={active ? 'page' : undefined}
              >
                <Icon
                  className={cn('h-[22px] w-[22px]', active ? 'text-primary-600' : 'text-gray-400')}
                  aria-hidden="true"
                />
                {label}
              </Link>
            </li>
          )
        })}
      </ul>
    </nav>
  )
}

